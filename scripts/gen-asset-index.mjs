#!/usr/bin/env node
/**
 * Generates src/audio/assets.generated.ts from assets/music/catalog.json and
 * assets/voice/catalog.json. Metro bundles an asset only through a static require(), so the app
 * cannot require catalog paths at run time; this script writes the static requires.
 *
 * Usage: node scripts/gen-asset-index.mjs           write the file
 *        node scripts/gen-asset-index.mjs --check   exit 1 when the file is missing or stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'audio', 'assets.generated.ts');

function readJson(rel) {
  const p = join(root, rel);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
}

const music = readJson('assets/music/catalog.json');
const voice = readJson('assets/voice/catalog.json');

const lines = [
  '// Generated by scripts/gen-asset-index.mjs from assets/music/catalog.json and assets/voice/catalog.json.',
  '// Do not edit by hand: run `npm run gen:assets`.',
  '',
  'export interface BundledTrack {',
  '  id: string;',
  '  title: string;',
  '  performer: string;',
  '  year: number;',
  '  source: number;',
  '}',
  '',
  'export const BUNDLED_TRACKS: BundledTrack[] = [',
];
for (const t of music?.tracks ?? []) {
  lines.push(
    `  { id: ${JSON.stringify(t.id)}, title: ${JSON.stringify(t.title)}, performer: ${JSON.stringify(t.performer)}, year: ${Number(t.year)}, source: require('../../assets/music/${t.file}') },`,
  );
}
lines.push('];', '', '/** Whispered clips by voice id, then message id. */', 'export const VOICE_CLIPS: Record<string, Record<string, number>> = {');
const byVoice = new Map();
for (const c of voice?.clips ?? []) {
  if (!byVoice.has(c.voice)) byVoice.set(c.voice, []);
  byVoice.get(c.voice).push(c);
}
for (const [v, clips] of [...byVoice.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(v)}: {`);
  for (const c of clips.sort((a, b) => a.message.localeCompare(b.message))) {
    lines.push(`    ${JSON.stringify(c.message)}: require('../../assets/voice/${c.file}'),`);
  }
  lines.push('  },');
}
lines.push('};', '');
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('src/audio/assets.generated.ts is stale: run `npm run gen:assets`.');
    process.exit(1);
  }
  console.log('gen-asset-index: OK');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${music?.tracks?.length ?? 0} tracks, ${voice?.clips?.length ?? 0} voice clips)`);
}
